@app.post("/student/{student_id}/export_guide")
def export_study_guide(student_id: str):
    """
    Invokes the LLM to generate a customized Markdown study guide
    for the student's weakest topics and exports it directly to the workspace disk.
    """
    from progress_tracking_agent import get_dashboard_summary
    from groq_client import Groq
    import json
    
    summary = get_dashboard_summary(student_id)
    weakest = summary.get("weakest_topics", [])
    
    if not weakest:
        graph = _load_graph()
        topics_list = list(graph.keys())
        fallback_topic = topics_list[0] if topics_list else "general_study"
        weakest = [{"topic": fallback_topic, "mastery": 0.0}]
        
    prompt = f"""You are an Expert Study Guide Writer Agent.
Your job is to write a highly detailed and helpful study guide for a student who is struggling with specific topics.

We have identified their weakest topics and mastery scores:
{json.dumps(weakest, indent=2)}

Create a detailed Markdown study guide. For EACH topic listed:
1. Explain the concept clearly and concisely using a helpful, easy-to-understand modality (e.g. Worked Example or Analogy).
2. Provide a detailed step-by-step solved problem.
3. Provide one practice question for the student to solve on their own, along with the expected final answer.

Format the output cleanly in Markdown, beginning with a '# Personalized Study Guide' header and a friendly opening statement.
Do not wrap it in anything other than clean markdown. Avoid generic chat intro/outro outside of the markdown document itself.
"""

    client = Groq(api_key=os.environ.get("GROQ_API_KEY") or "MOCK_KEY")
    try:
        response = client.chat.completions.create(
            model="llama-3.3-70b-versatile",
            messages=[
                {"role": "system", "content": "You are a helpful educational assistant that outputs clean, detailed Markdown content."},
                {"role": "user", "content": prompt},
            ],
            temperature=0.7,
        )
        content = response.choices[0].message.content
        
        filename = f"{student_id}_study_guide.md"
        filepath = os.path.join(os.path.dirname(__file__), filename)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)
            
        return {
            "status": "success",
            "filename": filename,
            "filepath": filepath,
            "message": f"Personalized study guide written to {filename}"
        }
    except Exception as e:
        filename = f"{student_id}_study_guide.md"
        filepath = os.path.join(os.path.dirname(__file__), filename)
        fallback_content = f"""# Personalized Study Guide for {student_id}

This is a fallback study guide. Please make sure to configure your `GROQ_API_KEY` in the `.env` file to generate a personalized guide.

## Weakest Topics to Review:
"""
        for t in weakest:
            fallback_content += f"- **{t['topic'].replace('_', ' ').title()}** (Current Mastery: {round(t['mastery']*100)}%)\n"
            
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(fallback_content)
            
        return {
            "status": "success",
            "filename": filename,
            "filepath": filepath,
            "message": f"Fallback study guide written to {filename} (Please configure GROQ_API_KEY for full guide)"
        }


@app.post("/student/{student_id}/generate_placement")
def generate_placement(student_id: str):
    """
    Generates a diagnostic test of exactly 10 questions covering topics in the active syllabus.
    """
    from curriculum_mapping_agent import _load_graph
    from groq import Groq
    import json
    
    graph = _load_graph()
    topics_list = list(graph.keys())
    
    if not topics_list:
        topics_list = ["linear_equations_isolation", "tcp_udp_reliability"]
        
    prompt = f"""You are an Expert Assessment Designer Agent.
Your job is to generate a diagnostic placement test of EXACTLY 10 questions to test a student's baseline knowledge.

Here is the list of topics in the active syllabus:
{json.dumps(topics_list)}

Generate exactly 10 questions. Distribute the questions across the topics. If there are fewer than 10 topics, create multiple different questions for the topics so that the total is EXACTLY 10.
Make the questions simple, clear, and direct (e.g., short-answer or math/logic problems that can be answered in a few words or lines).

Output ONLY a valid JSON object matching this schema, with no markdown wrappers or extra conversational text:
{{
  "test_id": "placement_{student_id}",
  "questions": [
    {{
      "question_id": 1,
      "topic": "<topic_id_matching_the_syllabus>",
      "question_text": "<clear question text>",
      "expected_answer": "<expected correct answer>"
    }}
  ]
}}
"""

    client = Groq(api_key=os.environ.get("GROQ_API_KEY") or "MOCK_KEY")
    try:
        response = client.chat.completions.create(
            model="llama-3.3-70b-versatile",
            messages=[
                {"role": "system", "content": "You are a specialized test designer agent that outputs ONLY valid JSON matching the specified schema."},
                {"role": "user", "content": prompt},
            ],
            temperature=0.7,
            response_format={"type": "json_object"},
        )
        data = json.loads(response.choices[0].message.content)
        _placement_tests[student_id] = data
        return data
    except Exception as e:
        print(f"[Placement Generation Fallback] LLM failed to generate placement test. Error: {e}")
        fallback_data = {
            "test_id": f"placement_{student_id}_fallback",
            "questions": []
        }
        for i in range(10):
            topic = topics_list[i % len(topics_list)]
            topic_clean = topic.replace("_", " ").title()
            fallback_data["questions"].append({
                "question_id": i + 1,
                "topic": topic,
                "question_text": f"Define and explain the core concept of {topic_clean}.",
                "expected_answer": f"A correct explanation of {topic_clean}."
            })
        _placement_tests[student_id] = fallback_data
        return fallback_data


@app.post("/student/{student_id}/submit_placement")
def submit_placement(student_id: str, req: SubmitPlacementRequest):
    """
    Submits student responses for the diagnostic placement test.
    Grades each response, logs them, and sets initial topic mastery scores.
    """
    from evaluator_agent import evaluate
    from memory_agent import update_mastery, log_error_event
    import json
    
    test = _placement_tests.get(student_id)
    if not test or test.get("test_id") != req.test_id:
        raise HTTPException(status_code=400, detail="Active placement test not found for this student.")
        
    results = []
    correct_count = 0
    
    for q in test["questions"]:
        q_id = q["question_id"]
        topic = q["topic"]
        expected = q["expected_answer"]
        student_ans = req.answers.get(str(q_id), req.answers.get(q_id, "")).strip()
        
        eval_res = evaluate(
            question=q["question_text"],
            rubric_or_expected_answer=expected,
            student_response=student_ans,
            target_skill=topic,
            current_mastery=0.5,
        )
        
        if isinstance(eval_res, list) and len(eval_res) > 0:
            eval_res = eval_res[0]
            
        is_correct = eval_res.get("is_correct", False)
        if is_correct:
            correct_count += 1
            update_mastery(student_id, topic, mastery_delta=0.3)
        else:
            update_mastery(student_id, topic, mastery_delta=-0.2)
            log_error_event(
                student_id=student_id,
                topic=topic,
                error_type=eval_res.get("error_classification", "conceptual"),
                meta={
                    "question": q["question_text"],
                    "student_answer": student_ans,
                    "correct_answer": expected
                }
            )
            
        results.append({
            "question_id": q_id,
            "topic": topic,
            "is_correct": is_correct,
            "score": eval_res.get("score", 0.0),
            "feedback": eval_res.get("feedback", "")
        })
        
    _placement_tests.pop(student_id, None)
    
    return {
        "status": "success",
        "total_questions": len(test["questions"]),
        "correct_answers": correct_count,
        "score_percentage": round((correct_count / len(test["questions"])) * 100),
        "results": results
    }


