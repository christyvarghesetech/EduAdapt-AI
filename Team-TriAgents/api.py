@app.post("/syllabus/from_file")
async def syllabus_from_file(file: UploadFile = File(...)):
    """
    For a file upload button. Accepts .txt directly; for .pdf/.docx you must
    extract text first (see note below) since this endpoint expects plain text.
    """
    if not file.filename.lower().endswith((".txt", ".md")):
        raise HTTPException(
            status_code=400,
            detail="Only .txt/.md accepted here. For PDF/DOCX, extract text "
                   "first (e.g. pdfplumber or python-docx) then call this "
                   "endpoint, or send extracted text to /syllabus/from_text.",
        )
    raw_bytes = await file.read()
    raw_text = raw_bytes.decode("utf-8", errors="ignore")
    graph = parse_and_save(raw_text)
    return {"status": "ok", "topics_extracted": len(graph), "graph": graph}


