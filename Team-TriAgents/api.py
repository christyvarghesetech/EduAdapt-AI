@app.post("/dev/seed")
def seed_data(student_id: str = "student_001"):
    db = _session()
    try:
        # Clear existing data for this student
        db.query(ErrorEvent).filter_by(student_id=student_id).delete()
        db.query(TopicMastery).filter_by(student_id=student_id).delete()
        db.query(StudentProfile).filter_by(student_id=student_id).delete()

        # 1. Profile
        profile = StudentProfile(student_id=student_id, learning_style="worked_example")
        db.add(profile)

        # 2. Topic Mastery
        now_utc = datetime.now(timezone.utc)
        topics = [
            ("osi_model_basics", 0.85, 4, now_utc - timedelta(days=4)),
            ("arithmetic_operations", 0.95, 5, now_utc - timedelta(days=3)),
            ("inverse_operations", 0.75, 3, now_utc - timedelta(days=2)),
            ("tcp_udp_reliability", 0.35, 6, now_utc - timedelta(days=1)),
            ("linear_equations_isolation", 0.60, 2, now_utc),
            ("packet_switching", 0.45, 5, now_utc - timedelta(hours=6)),
        ]
        for topic, mastery, attempts, updated_at in topics:
            tm = TopicMastery(
                student_id=student_id,
                topic=topic,
                mastery=mastery,
                attempts=attempts,
                last_updated=updated_at
            )
            db.add(tm)

        # 3. Error Events (Historical timeline)
        events = [
            ("osi_model_basics", "conceptual", "worked_example", 0.6, 0.15, 4),
            ("osi_model_basics", "careless_slip", "worked_example", 0.9, 0.10, 4),
            ("arithmetic_operations", "procedural", "visual", 0.7, 0.20, 3),
            ("arithmetic_operations", "careless_slip", "visual", 1.0, 0.05, 3),
            ("inverse_operations", "prerequisite", "analogy", 0.4, -0.05, 2),
            ("inverse_operations", "conceptual", "analogy", 0.85, 0.25, 2),
            ("tcp_udp_reliability", "conceptual", "socratic", 0.2, -0.10, 1),
            ("tcp_udp_reliability", "conceptual", "worked_example", 0.45, 0.15, 1),
            ("linear_equations_isolation", "procedural", "visual", 0.3, -0.05, 0),
            ("linear_equations_isolation", "procedural", "worked_example", 0.75, 0.25, 0),
            ("packet_switching", "prerequisite", "socratic", 0.5, 0.10, 0),
        ]
        for topic, err, method, score, delta, days_ago in events:
            ev = ErrorEvent(
                student_id=student_id,
                topic=topic,
                error_type=err,
                method_used=method,
                score=score,
                mastery_delta=delta,
                timestamp=now_utc - timedelta(days=days_ago)
            )
            db.add(ev)

        db.commit()
        return {"status": "success", "message": f"Seeded rich historical data for {student_id}"}
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=str(e))
    finally:
        db.close()


