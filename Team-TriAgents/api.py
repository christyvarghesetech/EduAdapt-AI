@app.post("/session/start")
def start_session(req: StartSessionRequest):
    """
    Kicks off the loop: runs DIAGNOSE -> TEACH -> QUIZ, then pauses and
    returns the generated quiz question, waiting for the student's answer.
    """
    orch = SessionOrchestrator(
        student_id=req.student_id,
        question=req.question,
        student_answer=req.student_answer,
        correct_answer=req.correct_answer,
        topic_hint=req.topic_hint,
    )
    session_id = f"{req.student_id}_{id(orch)}"
    _sessions[session_id] = orch

    # Run until we hit EVALUATE (i.e. a quiz question is ready for the student)
    while orch.state != LoopState.EVALUATE and orch.state != LoopState.DONE:
        orch.step()

    return {
        "session_id": session_id,
        "state": orch.state.name,
        "diagnosis": orch.context.get("diagnosis"),
        "curriculum_info": orch.context.get("curriculum_info"),
        "teach": orch.context.get("last_teach_result"),
        "quiz": orch.context.get("quiz"),
        "difficulty": orch.context.get("difficulty"),
    }


@app.post("/session/submit_answer")
def submit_answer(req: SubmitAnswerRequest):
    """
    Submits the student's answer to the current quiz question. Advances the
    loop through EVALUATE and either returns DONE, a new TEACH+QUIZ cycle
    (if the gap isn't closed yet), or a REPLAN escalation.
    """
    orch = _sessions.get(req.session_id)
    if not orch:
        raise HTTPException(status_code=404, detail="Session not found")

    orch.context["latest_student_response"] = req.student_response
    orch.step()  # runs EVALUATE

    response = {
        "session_id": req.session_id,
        "state": orch.state.name,
        "eval_result": orch.context.get("eval_result"),
        "current_mastery": orch.context.get("current_mastery"),
    }

    if orch.state == LoopState.TEACH:
        # Gap not closed — run the next teach+quiz cycle automatically
        while orch.state != LoopState.EVALUATE and orch.state != LoopState.DONE:
            orch.step()
        response["state"] = orch.state.name
        response["teach"] = orch.context.get("last_teach_result")
        response["quiz"] = orch.context.get("quiz")
        response["difficulty"] = orch.context.get("difficulty")

    elif orch.state == LoopState.REPLAN:
        orch.step()  # runs REPLAN
        response["state"] = orch.state.name
        response["replan_result"] = orch.context.get("replan_result")

    if orch.state == LoopState.DONE:
        del _sessions[req.session_id]  # session complete, free memory

    return response


@app.get("/session/{session_id}")
def get_session(session_id: str):
    orch = _sessions.get(session_id)
    if not orch:
        raise HTTPException(status_code=404, detail="Session not found")
    return {"state": orch.state.name, "context": orch.context}


